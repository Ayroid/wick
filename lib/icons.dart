/// Every icon by key, flattened. Built once — the picker and every render site
/// look up through it, and rebuilding a 250-entry map per habit per frame is
/// the kind of thing that only shows up on a long list.
final iconByKey = <String, IconData>{
  for (final group in iconGroups.values) ...group,
};

/// Which group a key belongs to, for the picker's search results.
final groupOfIcon = <String, String>{
  for (final entry in iconGroups.entries)
    for (final key in entry.value.keys) key: entry.key,
};

/// A habit with no icon chosen. The reference opens its picker here too.
const defaultIcon = 'activity';

/// The glyph for [key], or the default when the key is unknown — a stored icon
/// can outlive a rename, and a habit whose icon vanished should still draw.
IconData iconFor(String key) =>
    iconByKey[key] ?? iconByKey[defaultIcon] ?? LucideIcons.activity;
